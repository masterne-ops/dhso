SELECT '─── 按地市 × 专项 (业务员加总) vs 总负责 校验 ───' AS '';
WITH agg AS (
    SELECT 地市, 专项,
           SUM(CASE WHEN 是否地市总负责 = 'Y' THEN 目标台数 ELSE 0 END) AS 总责目标,
           SUM(CASE WHEN 是否地市总负责 = 'N' THEN 目标台数 ELSE 0 END) AS 业务员加总
      FROM focus_target_salesperson
     WHERE 年度 = 2026
     GROUP BY 1, 2
)
SELECT 地市, 专项, 总责目标, 业务员加总,
       CASE WHEN 总责目标 = 业务员加总 OR 总责目标 = 0 THEN '✓' ELSE '⚠️' END AS 校验
  FROM agg
 ORDER BY 地市, 专项;
