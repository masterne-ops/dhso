-- 业务员级专项目标(长表)
CREATE TABLE IF NOT EXISTS focus_target_salesperson (
    专项              TEXT NOT NULL,
    地市              TEXT NOT NULL,
    业务员            TEXT NOT NULL,
    年度              INTEGER NOT NULL,
    是否地市总负责    TEXT,             -- 'Y' / 'N'
    占比_pct          REAL,
    目标台数          INTEGER,
    备注              TEXT,
    更新人            TEXT,
    更新时间          TEXT,
    PRIMARY KEY (专项, 地市, 业务员, 年度)
);
CREATE INDEX IF NOT EXISTS idx_fts_focus ON focus_target_salesperson(专项);
CREATE INDEX IF NOT EXISTS idx_fts_city ON focus_target_salesperson(地市);
CREATE INDEX IF NOT EXISTS idx_fts_sp ON focus_target_salesperson(业务员);

